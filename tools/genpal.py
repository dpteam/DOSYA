"""Emit build/gen/pal.h so C code can say PAL_GREEN7 instead of 47."""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import pal  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "build", "gen", "pal.h")


def main():
    lines = ["/* generated by tools/genpal.py - do not edit */",
             "#ifndef DOSYA_PAL_H",
             "#define DOSYA_PAL_H",
             "",
             "#define PAL_BLACK 0",
             "#define PAL_TRANSPARENT 0"]
    for name, idx in pal.PAL.items():
        lines.append("#define PAL_%s %d" % (name.upper(), idx))
    lines.append("")
    for name, (stops, n) in pal.RAMPS.items():
        lines.append("#define PAL_%s_BASE %d" % (name.upper(), pal.PAL[name + "0"]))
        lines.append("#define PAL_%s_N %d" % (name.upper(), n))
    lines.append("")
    lines.append("#define PAL_SHADOW PAL_VOID1")
    lines.append("")
    lines.append("#endif")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(pal.PAL), "entries")


if __name__ == "__main__":
    main()
