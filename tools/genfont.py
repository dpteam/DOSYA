"""Build an 8x16 CP866 font blob from GNU Unifont.

Unifont ships a .hex file: "<codepoint>:<hex rows>". We pull the 8-pixel-wide
glyphs for every character in the CP866 codepage (that is what a Russian DOS
game in 1993 would have had) and emit a 256*16 byte table.
"""
import gzip
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HEX = os.path.join(ROOT, "vendor", "unifont.hex.gz")
OUT = os.path.join(ROOT, "build", "gen", "font.c")


def load_unifont():
    glyphs = {}
    with gzip.open(HEX, "rt", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            cp, data = line.split(":")
            glyphs[int(cp, 16)] = data
    return glyphs


def to_8x16(data):
    """Unifont hex -> 16 rows of 8 bits, or None if it is a 16-wide glyph."""
    rows = [int(data[i:i + 2], 16) for i in range(0, len(data), 2)]
    if len(rows) == 16:
        return rows
    if len(rows) == 32:  # 16x16 double-width; squeeze by taking the right half
        return [rows[i * 2 + 1] for i in range(16)]
    return None


def cp866_map():
    """byte value -> unicode char, via the real codec."""
    m = {}
    for i in range(256):
        try:
            m[i] = bytes([i]).decode("cp866")
        except UnicodeDecodeError:
            m[i] = None
    return m


def build_table():
    """Return the 256*16 CP866 bitmap as bytes, plus a list of missing chars.

    Exposed as a function so tools/gen_icon.py can draw the title in the same
    font the game uses, instead of shipping a second copy of the glyphs.
    """
    uf = load_unifont()
    cmap = cp866_map()
    table = bytearray(256 * 16)
    missing = []
    for code in range(256):
        ch = cmap.get(code)
        if ch is None or code < 32:
            continue
        rows = uf.get(ord(ch))
        if rows is None:
            missing.append((code, ch))
            continue
        r = to_8x16(rows)
        if r is None:
            missing.append((code, ch))
            continue
        table[code * 16:code * 16 + 16] = bytes(r)
    return table, missing


def main():
    table, missing = build_table()
    if missing:
        print("missing:", missing[:20], file=sys.stderr)

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="ascii") as f:
        f.write("/* generated by tools/genfont.py - GNU Unifont, CP866 layout */\n")
        f.write("const unsigned char g_font[256*16] = {\n")
        for code in range(256):
            row = table[code * 16:code * 16 + 16]
            f.write("  " + ",".join("0x%02x" % b for b in row) + ",  /* %d */\n" % code)
        f.write("};\n")
    print("wrote", OUT, len(table), "bytes")


if __name__ == "__main__":
    main()
