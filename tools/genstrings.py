def c_lit(s):
    out = []
    for b in s.encode("cp866"):
        if b == 0x22:
            out.append('\\"')
        elif b == 0x5C:
            out.append("\\\\")
        elif 32 <= b < 127:
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    lines = ["/* generated by tools/genstrings.py - do not edit */",
             "#ifndef DOSYA_STRINGS_H",
             "#define DOSYA_STRINGS_H",
             ""]
    for k, v in S.items():
        lines.append("#define S_%s %s" % (k, c_lit(v)))
    lines.append("")
    lines.append("/* death text, grouped by cause */")
    for group, prefix in (("WATER", "DIE_WATER_"), ("FALL", "DIE_FALL_"),
                          ("SPIKE", "DIE_SPIKE_"), ("ENEMY", "DIE_ENEMY_")):
        keys = [k for k in S if k.startswith(prefix)]
        lines.append("static const char *g_die_%s[] = {" % group.lower())
        for k in keys:
            lines.append("  S_%s," % k)
        lines.append("  0")
        lines.append("};")
        lines.append("#define N_DIE_%s %d" % (group, len(keys)))
        lines.append("")
    lines.append("static const char **g_die_lists[] = {")
    lines.append("  g_die_water, g_die_fall, g_die_spike, g_die_enemy")
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    with open(OUT, "w", encoding="ascii") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", OUT, len(S), "strings")


if __name__ == "__main__":
    main()
